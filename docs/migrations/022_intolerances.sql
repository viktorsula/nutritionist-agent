-- =============================================
-- Миграция 022: Разделение аллергий и непереносимостей (P1-13, шаг 1)
-- =============================================
-- Контекст: до сих пор аллергия и пищевая непереносимость лежали в ОДНОМ поле
-- client_profiles.allergies (анкета задавала один вопрос «Аллергия/непереносимость
-- продуктов?»). Медицински это разные вещи с разными последствиями:
--
--   • аллергия (иммунный ответ на белок) — абсолютная, дозонезависимая; опасны даже
--     следовые количества; реакция может быть тяжёлой;
--   • непереносимость (ферментная, напр. лактазная недостаточность) — дозозависимая
--     и зависит от вида продукта: при непереносимости лактозы козий или овечий сыр
--     часто допустим, а коровье молоко — нет.
--
-- Пока эти два состояния неразличимы в данных, никакая проверка продуктов (ни
-- подстрочная, ни смысловая) не может дать верный ответ: у неё просто нет входных
-- данных, чтобы отличить «нельзя вообще» от «зависит от вида и количества».
-- Спецификация решения: docs/docs/diagnostic_report.md, блок решений по P1-13/P2-1.
-- =============================================

ALTER TABLE client_profiles
    ADD COLUMN IF NOT EXISTS intolerances TEXT[];

COMMENT ON COLUMN client_profiles.allergies IS
    'Аллергии (иммунный ответ): абсолютный запрет, дозонезависимо, опасны следовые '
    'количества. Severity алерта — critical.';

COMMENT ON COLUMN client_profiles.intolerances IS
    'Пищевые непереносимости (ферментные и пр.): дозозависимы, зависят от вида продукта '
    '(напр. при лактазной недостаточности козий сыр часто допустим). Severity — medium, '
    'решение об исключении принимает нутрициолог.';

-- ВАЖНО: данные существующих клиентов НЕ переносятся автоматически. Разделить
-- «аллергия» и «непереносимость» в уже введённом свободном тексте невозможно без
-- врачебной трактовки — всё остаётся в allergies (то есть в более строгой категории,
-- что безопасно), а нутрициолог переносит непереносимости вручную в карточке клиента.

