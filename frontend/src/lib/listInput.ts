/**
 * Разбор списка, введённого свободным текстом (ограничения плана, аллергии,
 * непереносимости).
 *
 * Проблема, которую это решает (P1-13): раньше строка резалась по запятой всегда, и
 * уточнение внутри пункта разваливалось на мусор — «молочные продукты, кроме козьего»
 * превращалось в два ограничения: «молочные продукты» (запрещает лишнее) и «кроме
 * козьего» (бессмысленное). При этом нюанс вида «кроме козьего» — именно та информация,
 * без которой проверка продуктов не может дать верный ответ.
 *
 * Правило: если в тексте есть переводы строки — разделителем считается ТОЛЬКО перевод
 * строки, запятые остаются частью пункта. Если переводов строки нет — работает привычное
 * деление по запятой и точке с запятой, чтобы простое «орехи, молоко» не превратилось в
 * один пункт.
 *
 * splitListInput("орехи, молоко")                       → ["орехи", "молоко"]
 * splitListInput("молочные, кроме козьего\nглютен")     → ["молочные, кроме козьего", "глютен"]
 */
export function splitListInput(v: unknown): string[] {
  if (typeof v !== "string" || !v.trim()) return [];
  const separator = v.includes("\n") ? /\n+/ : /[,;]+/;
  return v
    .split(separator)
    .map((s) => s.trim())
    .filter(Boolean);
}

/**
 * Обратная операция — список в текст для редактирования. Всегда по строке на пункт:
 * иначе пункт с запятой внутри при повторном сохранении развалился бы.
 */
export function joinListInput(items?: string[] | null): string {
  return (items ?? []).join("\n");
}
